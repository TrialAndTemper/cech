package build

import (
	"slices"
	"strings"

	"github.com/TrialAndTemper/cech/cli/internal/marketplace"
)

// CodeOwnersPath is the code owners file GitHub reads.
const CodeOwnersPath = ".github/CODEOWNERS"

// codeOwnersMark starts every code owners file the build writes, in
// each version of its header.
const codeOwnersMark = "# Generated by cech build"

// CodeOwners returns the code owners file of ADR 13 item 4: a catch-all
// line for the marketplace's team, then for each plugin its folder,
// owned by the plugin's owner and its further maintainers. A plugin
// whose line would name nobody gets no line.
func CodeOwners(m *marketplace.Marketplace) []byte {
	var b strings.Builder
	b.WriteString(codeOwnersMark + " from data/marketplace.toml and each plugin's\n")
	b.WriteString("# plugin.json; do not edit.\n\n")
	b.WriteString("* " + m.Data.Team + "\n")
	for _, p := range m.Plugins {
		var users []string
		add := func(user string) {
			if !slices.ContainsFunc(users, func(u string) bool { return strings.EqualFold(u, user) }) {
				users = append(users, user)
			}
		}
		if user := owner(p.AuthorURL); user != "" && !strings.EqualFold(user, m.Data.Org()) {
			add(user)
		}
		for _, user := range p.Maintainers {
			add(user)
		}
		if len(users) == 0 {
			continue
		}
		b.WriteString("/" + p.Dir() + "/")
		for _, user := range users {
			b.WriteString(" @" + user)
		}
		b.WriteString("\n")
	}
	return []byte(b.String())
}

// owner returns the GitHub user name in an author url of the form
// https://github.com/<user>, or "" for a url of any other form. It
// reads the url only, without network access.
func owner(url string) string {
	user, ok := strings.CutPrefix(url, "https://github.com/")
	if !ok || !marketplace.IsGitHubUser(user) {
		return ""
	}
	return user
}
