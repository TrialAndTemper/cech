package build

import (
	"slices"
	"strings"

	"github.com/TrialAndTemper/cech/cli/internal/marketplace"
)

// PagePath is the catalogue page, for people browsing the marketplace.
const PagePath = "docs/catalogue.md"

var cellEscaper = strings.NewReplacer(`\`, `\\`, "<", `\<`, "|", `\|`)

// Page returns the catalogue page: a table of the categories, CECH's
// and then any the marketplace adds, with what each holds, and a table
// of plugins and their descriptions per category. A text goes on one
// line, with runs of white space as one space, and \, < and | escaped,
// so it stays in its cell and holds no HTML.
func Page(m *marketplace.Marketplace) []byte {
	var b strings.Builder
	b.WriteString("<!-- Generated by cech build from data/marketplace.toml, CECH's categories and each plugin's SKILL.md; do not edit. -->\n\n")
	b.WriteString("# Plugin catalogue\n\n")
	if len(m.Plugins) == 0 {
		b.WriteString("The `" + m.Data.Namespace + "` marketplace has no plugins yet.\n")
	} else {
		b.WriteString("The plugins of the `" + m.Data.Namespace + "` marketplace, by category.\n")
	}
	b.WriteString("\n## Categories\n\n")
	b.WriteString("| Category | Holds |\n")
	b.WriteString("| --- | --- |\n")
	for _, c := range slices.Concat(marketplace.CECHCategories, m.Data.Categories) {
		b.WriteString("| `" + c.Name + "` | " + cell(c.Holds) + " |\n")
	}
	category := ""
	for _, p := range m.Plugins {
		if p.Category != category {
			category = p.Category
			b.WriteString("\n## `" + category + "`\n\n")
			b.WriteString("| Plugin | Description |\n")
			b.WriteString("| --- | --- |\n")
		}
		b.WriteString("| `" + p.Name + "` | " + cell(p.Description) + " |\n")
	}
	return []byte(b.String())
}

// cell returns s as the text of a table cell.
func cell(s string) string {
	return cellEscaper.Replace(strings.Join(strings.Fields(s), " "))
}
