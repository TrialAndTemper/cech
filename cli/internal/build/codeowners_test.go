package build

import (
	"testing"

	"github.com/TrialAndTemper/cech/cli/internal/marketplace"
)

func TestCodeOwners(t *testing.T) {
	m := &marketplace.Marketplace{
		Data: marketplace.Data{Namespace: "acme", Team: "@Acme/maintainers"},
		Plugins: []marketplace.Plugin{
			{Category: "tool", Name: "a-org", AuthorURL: "https://github.com/acme"},                                         // the org itself: the catch-all covers it
			{Category: "tool", Name: "b-slash", AuthorURL: "https://github.com/alice/"},                                     // not exactly https://github.com/<user>
			{Category: "tool", Name: "c-http", AuthorURL: "http://github.com/alice"},                                        // http, not https
			{Category: "tool", Name: "d-none", Maintainers: []string{"bob"}},                                                // maintainers only
			{Category: "tool", Name: "e-dup", AuthorURL: "https://github.com/Carol", Maintainers: []string{"carol", "dan"}}, // carol twice, by case
		},
	}
	want := `# Generated by cech build from data/marketplace.toml and each plugin's
# plugin.json; do not edit.

* @Acme/maintainers
/plugins/tool/d-none/ @bob
/plugins/tool/e-dup/ @Carol @dan
`
	if got := string(CodeOwners(m)); got != want {
		t.Errorf("got\n%s\nwant\n%s", got, want)
	}
}
