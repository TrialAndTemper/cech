package codex

import (
	"testing"

	"github.com/BurntSushi/toml"
)

func TestAgent(t *testing.T) {
	got := string(Agent("acme-reviewer.md", "acme-reviewer", "Reviews \"work\".",
		"\n\nCheck the change.\n\n- One\n- Two\n\n"))
	want := `# Generated by cech build from acme-reviewer.md; do not edit.
name = "acme-reviewer"
description = "Reviews \"work\"."
sandbox_mode = "read-only"
developer_instructions = """
Check the change.

- One
- Two
"""
`
	if got != want {
		t.Errorf("got\n%s\nwant\n%s", got, want)
	}
}

// TestAgentReadsBack checks that a TOML parser reads every field back
// as it was given, whatever the text holds.
func TestAgentReadsBack(t *testing.T) {
	tests := []struct {
		name, description, instructions string
	}{
		{"quotes and backslashes", `Says "hi" \ bye`, "Three quotes: \"\"\" and a \\ at the end\\\n"},
		{"control characters", "tab\there\nnew line\rreturn", "tab\tkept\x00nul \x7f del \x1b esc\n"},
		{"unicode", "Café — naïve ✓", "Zażółć gęślą jaźń\n"},
		{"empty instructions", "d", ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var got struct {
				Name                  string `toml:"name"`
				Description           string `toml:"description"`
				SandboxMode           string `toml:"sandbox_mode"`
				DeveloperInstructions string `toml:"developer_instructions"`
			}
			src := Agent("x.md", "x", tt.description, tt.instructions)
			meta, err := toml.Decode(string(src), &got)
			if err != nil {
				t.Fatalf("%v in\n%s", err, src)
			}
			if keys := meta.Undecoded(); len(keys) > 0 {
				t.Errorf("unexpected keys %v", keys)
			}
			if got.Name != "x" || got.Description != tt.description || got.SandboxMode != "read-only" ||
				got.DeveloperInstructions != tt.instructions {
				t.Errorf("read back %+v from\n%s", got, src)
			}
		})
	}
}
