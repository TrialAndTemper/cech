// Package codex holds what cech knows of Codex (ADR 15 item 6).
package codex

import (
	"fmt"
	"strings"
)

// Agent renders a reviewer agent written for Claude Code as a Codex
// custom agent file. Codex ignores agents that a plugin bundles, so the
// build writes this file beside the agent's Markdown, and cech copies it
// into a project's .codex/agents/ (ADR 10 item 3): the workaround of
// the harness data file's entry codex-plugin-agents (ADR 15 item 6).
//
// The file holds the three fields Codex requires, name, description and
// developer_instructions, and sandbox_mode = "read-only", since a CECH
// plugin's agents are read-only reviewers (ADR 11 item 2). It starts
// with a comment naming source, the Markdown it came from.
func Agent(source, name, description, instructions string) []byte {
	instructions = strings.TrimLeft(instructions, "\n")
	instructions = strings.TrimRight(instructions, " \t\n")
	if instructions != "" {
		instructions += "\n"
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by cech build from %s; do not edit.\n", source)
	fmt.Fprintf(&b, "name = \"%s\"\n", escape(name, false))
	fmt.Fprintf(&b, "description = \"%s\"\n", escape(description, false))
	b.WriteString("sandbox_mode = \"read-only\"\n")
	// The line end right after the opening quotes is not part of the
	// string.
	fmt.Fprintf(&b, "developer_instructions = \"\"\"\n%s\"\"\"\n", escape(instructions, true))
	return []byte(b.String())
}

// escape escapes s for a TOML basic string, or with multiline for a
// multiline one, which keeps its line ends and tabs as they are. Every
// quote is escaped, so no run of three can end the string.
func escape(s string, multiline bool) string {
	var b strings.Builder
	for _, r := range s {
		switch {
		case r == '"' || r == '\\':
			b.WriteByte('\\')
			b.WriteRune(r)
		case multiline && (r == '\n' || r == '\t'):
			b.WriteRune(r)
		case r == '\t':
			b.WriteString(`\t`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\r':
			b.WriteString(`\r`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u%04X`, r)
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}
